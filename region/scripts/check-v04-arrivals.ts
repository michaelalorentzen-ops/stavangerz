/** Real arrivals get real positions; existing canonical gaps are never repaired by guessing. */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { newRegionGame, startRegionDay, recruit, prepareGearPlan } from '../packages/gameplay/src/region/engine';
import { ensureMobility, beginMission, returnMission } from '../packages/gameplay/src/region/mobility';
import { centralAvailablePopulation } from '../packages/gameplay/src/region/administration';
import type { RegionWorld, ReportLine } from '../packages/gameplay/src/region/types';
const source=JSON.parse(readFileSync('apps/game-client/public/world/region-v1.json','utf8')) as RegionWorld;
const template=source.zones.find(z=>z.level===3)!;
const world:RegionWorld={...source,zones:['home','field'].map(id=>({...template,id,name:id,measures:{...template.measures!,homes:0,floor:0}})),neighbours:[{a:'home',b:'field',borderM:5}],links:[],pois:[],starts:[]};
const fresh=()=>{const s=newRegionGame(world,'home',51);delete s.event;s.phase=2;s.stock.food=s.stock.water=200;for(const z of Object.values(s.zones)){z.zombies=0;z.status='scouted';z.intel={min:0,max:0,day:0};}ensureMobility(s);return s;};
const promoted=fresh();promoted.population.adults=6;delete promoted.crewPositions!.ingrid;
const oldIds=new Set(promoted.survivors.map(p=>p.id));
const result=startRegionDay(promoted,world,[]);
const newPeople=result.state.survivors.filter(p=>!oldIds.has(p.id));
assert.equal(newPeople.length,1,'The actual central society promotion was exercised');
const leader=newPeople[0];
assert.deepEqual(result.state.crewPositions![leader.id],{kind:'zone',zoneId:'home'});
assert.deepEqual(prepareGearPlan(result.state,world,[{id:'available',action:'rest',zoneId:'home',survivorIds:[leader.id]}]).errors,[],'The promoted leader is usable rather than permanently disabled');
assert.equal(result.state.crewPositions!.ingrid,undefined,'A pre-existing canonical gap stays unknown');
assert.equal(centralAvailablePopulation(result.state).adults,5,'Exactly one actual central adult becomes named');
const onlyRemote=fresh();onlyRemote.population.adults=6;onlyRemote.mobility!.depotResidents={field:{adults:6,children:0,elderly:0,sick:0}};
const remoteResult=startRegionDay(onlyRemote,world,[]);
assert.equal(remoteResult.state.survivors.length,onlyRemote.survivors.length,'Regional/depot adults do not teleport into central named crew');
const rescued=fresh();const mission=beginMission(rescued,world,{id:'rescue',action:'search',zoneId:'field',survivorIds:['marius']});
const initialIds=new Set(rescued.survivors.map(p=>p.id));const lines:ReportLine[]=[];
recruit(rescued,lines,'Funnet i felt',()=>0,{zoneId:'field',missionId:mission.id});
const arrival=rescued.survivors.find(p=>!initialIds.has(p.id))!;
assert.ok(arrival);assert.deepEqual(rescued.crewPositions![arrival.id],{kind:'zone',zoneId:'field'});
assert.ok(mission.survivorIds.includes(arrival.id),'The rescued person physically joins the returning party');
assert.equal(rescued.gear!.items.filter(i=>i.id===`starter:${arrival.id}`).length,1,'The new personal weapon is materialized once');
mission.routeZoneIds=['home','field'];mission.routeIndex=1;
returnMission(rescued,world,mission,10,lines);
assert.deepEqual(rescued.crewPositions![arrival.id],{kind:'zone',zoneId:'home'},'The rescued person arrives only with the actual return route');
console.log('PASS arrivals: central promotion, no allocated-population teleport, actual field rescue and return, usable gear, preserved unknown canonical entries.');
