/** Physical late-game community: one population and depot ledger. */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { newRegionGame } from '../packages/gameplay/src/region/engine';
import type { Population, RegionState, RegionWorld, ReportLine } from '../packages/gameplay/src/region/types';
import { applyAdministrationCommand, administrations, centralAvailablePopulation, centralCommunity, regionalCommunity, regionalDay, regionalL1, regionalMandate, regionalStock, regionalSupplyRequest, type AdministrationGame } from '../packages/gameplay/src/region/administration';
import { dailyFlows } from '../packages/gameplay/src/region/economy';
import { societyDay, workforce } from '../packages/gameplay/src/region/society';
const world = JSON.parse(readFileSync('apps/game-client/public/world/region-v1.json', 'utf8')) as RegionWorld;
const home = world.starts[0].zoneId;
const remote = world.zones.find(z => z.level === 3 && regionalL1(world, z.id) !== regionalL1(world, home))!;
const zero = (): Population => ({ adults: 0, children: 0, elderly: 0, sick: 0 });
function fresh(): AdministrationGame {
  const state = newRegionGame(world, home, 42) as AdministrationGame;
  state.event = undefined; state.phase = 4; state.population = { adults: 20, children: 4, elderly: 2, sick: 0 }; state.stock.food = 500; state.stock.water = 500;
  state.zones[remote.id].status = 'controlled'; state.zones[remote.id].zombies = 0;
  state.crewPositions = Object.fromEntries(state.survivors.map(s => [s.id, { kind: 'zone' as const, zoneId: home }]));
  state.crewPositions[state.survivors[1].id] = { kind: 'zone', zoneId: remote.id };
  return state;
}
const legacy = fresh(); const serialized = JSON.stringify(legacy);
assert.deepEqual(administrations(legacy), []); assert.deepEqual(centralAvailablePopulation(legacy), legacy.population); assert.equal(JSON.stringify(legacy), serialized);
assert.throws(() => applyAdministrationCommand(legacy, world, { kind: 'establish', hqZoneId: remote.id, leaderId: legacy.survivors[0].id }), /reise fysisk/);
let state = applyAdministrationCommand(legacy, world, { kind: 'establish', hqZoneId: remote.id, leaderId: legacy.survivors[1].id }) as AdministrationGame;
assert.equal(JSON.stringify(legacy), serialized, 'Commands are pure');
let region = administrations(state)[0];
assert.deepEqual(region.residents, zero()); assert.deepEqual(regionalStock(state, region), {});
assert.deepEqual(state.stock, legacy.stock, 'Establishment cannot teleport a budget');
state = applyAdministrationCommand(state, world, { kind: 'budget', l1Id: region.l1Id, budget: { food: 40, water: 30 } }) as AdministrationGame;
region = administrations(state)[0];
assert.deepEqual(regionalSupplyRequest(state, region), { food: 40, water: 30 }); assert.equal(state.stock.food, 500);
assert.throws(() => applyAdministrationCommand(state, world, { kind: 'residents', l1Id: region.l1Id, residents: { ...zero(), adults: 10 } }), /transporteres fysisk/);
state.mobility!.depotResidents = { [remote.id]: { ...zero(), adults: 8, children: 2 } };
const empireBefore = { ...state.population };
assert.equal(centralAvailablePopulation(state).adults, 12);
state = applyAdministrationCommand(state, world, { kind: 'residents', l1Id: region.l1Id, residents: { ...zero(), adults: 8, children: 2 } }) as AdministrationGame;
region = administrations(state)[0]; assert.deepEqual(state.population, empireBefore); assert.equal(centralAvailablePopulation(state).adults, 12); assert.equal(workforce(state), 12);
assert.deepEqual(state.mobility!.depotResidents![remote.id], zero(), 'Residents consumed from delivered pool once');
const centralFlow = dailyFlows(state, world); const localFlow = dailyFlows(regionalCommunity(state, world, region), world);
assert.equal(centralFlow.zones[remote.id], undefined, 'Delegated land cannot produce into central stock');
assert.ok(localFlow.zones[remote.id], 'Local land produces only locally');
const centralCrew = state.survivors.length - 1;
assert.equal(centralFlow.water.drunk, centralCrew + 12 + 2 * .6 + 2 * .8, 'Remote named leader and allocated dependents are not fed centrally');
state.mobility!.depots[remote.id] = { food: 100, water: 100, medicine: 10 };
const stockBefore = structuredClone(state.stock); const lines: ReportLine[] = [];
regionalDay(state, world, lines, () => .99);
assert.deepEqual(state.stock, stockBefore, 'Regional settlement never draws remote global resources');
assert.ok(region.ledger); assert.equal(Object.values(region.work).reduce((n, x) => n + x, 0), 8);
assert.ok(Object.values(regionalStock(state, region)).every(n => n >= 0));
const afterDay = JSON.stringify(state); regionalDay(state, world, lines); assert.equal(JSON.stringify(state), afterDay, 'Settlement hook is idempotent for same day');
const reconstructed = JSON.parse(JSON.stringify(state)) as RegionState; assert.deepEqual(administrations(reconstructed), administrations(state), 'Optional state survives region-2 JSON roundtrip');
const death = fresh(); const orphan = applyAdministrationCommand(death, world, { kind: 'establish', hqZoneId: remote.id, leaderId: death.survivors[1].id }) as AdministrationGame;
orphan.survivors[1].alive = false; regionalDay(orphan, world, [], () => .99); assert.equal(administrations(orphan)[0].leaderId, undefined); assert.ok(administrations(orphan)[0].alerts.some(a => a.includes('leder')));
assert.equal(regionalMandate({ ...state, laws: ['council'] }).automaticSuccession, false); assert.equal(regionalMandate({ ...state, laws: ['strongman'] }).automaticSuccession, false);
const regionalPopBefore = { ...region.residents }; societyDay(state, world, [], () => .99); assert.deepEqual(region.residents, regionalPopBefore, 'Global disease/accidents cannot consume local population');
// Central work cannot discover a regional zone or consume its population on death.
const scope = centralCommunity(state, world);
assert.equal(scope.state.zones[remote.id], undefined);
assert.equal(scope.world.zones.find(z => z.id === remote.id), undefined);
const oldEmpire = state.population.adults;
scope.state.population.adults -= 1; scope.commit(state);
assert.equal(state.population.adults, oldEmpire - 1);
assert.deepEqual(region.residents, regionalPopBefore);
// Active passengers and delivered nonregional communities remain subsets, never new people.
const travelling = fresh();
travelling.crewMissions = { transport: { id: 'transport', orderId: 'transport', action: 'search', survivorIds: [], originZoneId: home, targetZoneId: remote.id, issuedDay: 0, status: 'outbound', passengers: { ...zero(), adults: 3, children: 1 } } } as RegionState['crewMissions'];
assert.equal(centralAvailablePopulation(travelling).adults, 17);
assert.equal(travelling.population.adults, 20);
// Local starvation cannot be masked by a full global store. Death decrements both representations once.
const hungry = applyAdministrationCommand(fresh(), world, { kind: 'establish', hqZoneId: remote.id, leaderId: legacy.survivors[1].id }) as AdministrationGame;
const hungryRegion = administrations(hungry)[0];
hungryRegion.residents = { ...zero(), adults: 10 };
hungryRegion.leaderId = undefined; hungry.day = 3;
hungry.mobility!.depots[remote.id] = {};
hungry.zones[remote.id].upgrades = [];
const healthBefore = hungry.survivors[1].health;
regionalDay(hungry, world, [], () => .99);
assert.ok((hungryRegion.ledger?.shortages.food ?? 0) > 0);
assert.ok(hungry.survivors[1].health < healthBefore);
assert.equal(hungry.stock.food, 500);
assert.equal(hungryRegion.residents.adults, 9);
assert.equal(hungry.population.adults, 19);
console.log('v0.4 administration: commands, legacy, physical people/stock, disjoint flows/work, budgets, idempotence and leader loss passed.');
