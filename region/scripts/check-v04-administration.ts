function fresh(): AdministrationGame {
  const state = newRegionGame(world, home, 42) as AdministrationGame;
  state.event = undefined; state.phase = 4; state.population = { adults: 20, children: 4, elderly: 2, sick: 0 }; state.stock.food = 500; state.stock.water = 500;
  state.zones[remote.id].status = 'controlled'; state.zones[remote.id].zombies = 0;
  state.crewPositions = Object.fromEntries(state.survivors.map(s => [s.id, { kind: 'zone' as const, zoneId: home }]));
  state.crewPositions[state.survivors[1].id] = { kind: 'zone', zoneId: remote.id };
  return state;
}
